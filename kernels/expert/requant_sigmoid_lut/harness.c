static int8_t ref_element(int32_t ai, int32_t mult, int shift, int8_t zp,
                           const int8_t lut[256]) {
    int64_t v    = (int64_t)ai * (int64_t)mult;
    int64_t half = shift > 0 ? ((int64_t)1 << (shift - 1)) : 0;
    int64_t r    = (v >= 0) ? ((v + half) >> shift) : -(((-v) + half) >> shift);
    r += zp;
    if (r < 0)   r = 0;
    if (r > 255) r = 255;
    return lut[(uint8_t)r];
}

/* Param sweep: 3 sets x 2 LUTs = 6 total sweeps */
static const int32_t MULTS[]  = {  5,  1, 13 };
static const int     SHIFTS[] = {  4,  0,  7 };
static const int     ZPS[]    = {  0,  0, -5 };
#define NSETS ((int)(sizeof(MULTS)/sizeof(MULTS[0])))

int main(void) {
    uint32_t s = 0xDECA1337u;
    for (int i = 0; i < N; i++) a[i] = (int32_t)((int32_t)(hvx_lcg(&s)) % 601) - 300;
    /* Edge cases: values that land at idx=0 and idx=255, and negative inputs */
    a[0] = 300; a[1] = -300; a[2] = 0; a[3] = 1; a[4] = -1;
    a[5] = -1000; a[6] = 1000;

    int errors = 0, fb = -1; long gotv = 0, expv = 0;
    int total = 0;

    const int8_t *luts[2] = { LUT_A, LUT_B };
    for (int lut_i = 0; lut_i < 2; lut_i++) {
        const int8_t *lut = luts[lut_i];
        for (int k = 0; k < NSETS; k++) {
            int32_t mult = MULTS[k]; int shift = SHIFTS[k]; int8_t zp = (int8_t)ZPS[k];
            for (int i = 0; i < N; i++) ref[i] = ref_element(a[i], mult, shift, zp, lut);
            for (int i = 0; i < N; i++) out[i] = (int8_t)0xA5;
            unsigned long long _hvx_kc = 0;
            HVX_TIME_KERNEL(_hvx_kc, { candidate_kernel(a, out, N, mult, shift, zp, lut); });
            printf("HVXENV_KCYCLES kernel=%llu\n", _hvx_kc);
            for (int i = 0; i < N; i++) {
                if (out[i] != ref[i]) {
                    errors++;
                    if (fb < 0) { fb = total + i; gotv = (long)out[i]; expv = (long)ref[i]; }
                }
            }
            total += N;
        }
    }
    hvx_report(errors, total, fb, gotv, expv);
    return errors ? 1 : 0;
}
